create or replace function public.add_combo_to_order(
  target_order_id uuid,
  target_combo_id uuid,
  target_quantity numeric default 1
)
returns public.order_items
language plpgsql
security definer
set search_path = public
as $$
declare
  order_row public.orders;
  combo_row public.combos;
  component_row public.combo_components;
  product_row public.products;
  service_row public.services;
  item_row public.order_items;
  required_quantity numeric(14,3);
  available_quantity numeric;
  component_cost numeric(14,4);
  total_cost numeric(14,2) := 0;
begin
  if target_quantity <= 0 then raise exception 'Quantity must be greater than zero.'; end if;

  select * into order_row from public.orders where id = target_order_id for update;
  if order_row.id is null then raise exception 'Order was not found.'; end if;
  if order_row.status <> 'open' then raise exception 'Only open orders can be changed.'; end if;
  if not public.can_work_with_orders(order_row.organization_id) then raise exception 'You do not have access to this order.'; end if;

  select * into combo_row from public.combos where id = target_combo_id;
  if combo_row.id is null then raise exception 'Combo was not found.'; end if;
  if combo_row.organization_id <> order_row.organization_id or combo_row.status <> 'active' then
    raise exception 'Combo is not active in this organization.';
  end if;
  if combo_row.selection_mode <> 'fixed' then
    raise exception 'Only fixed combos are supported at this stage.';
  end if;

  for component_row in
    select * from public.combo_components
    where combo_id = combo_row.id
    order by sort_order asc, created_at asc
  loop
    if component_row.component_type = 'product' then
      select * into product_row from public.products where id = component_row.product_id for update;
      if product_row.id is null or product_row.status <> 'active' or product_row.organization_id <> order_row.organization_id then
        raise exception 'Combo product component is not active.';
      end if;

      required_quantity := component_row.quantity * target_quantity;
      if product_row.track_stock then
        available_quantity := public.calculate_available_product_stock(product_row.id);
        if available_quantity < required_quantity then
          raise exception 'Not enough available stock for combo component %. Available: %.', product_row.name, available_quantity;
        end if;
      end if;

      total_cost := total_cost + (product_row.average_purchase_cost * required_quantity);
    end if;
  end loop;

  perform set_config('app.order_write', '1', true);

  insert into public.order_items (
    organization_id,
    order_id,
    item_type,
    combo_id,
    name_snapshot,
    description_snapshot,
    image_path_snapshot,
    quantity,
    unit_price,
    total_price,
    unit_cost_snapshot,
    total_cost_snapshot,
    metadata,
    added_by
  )
  values (
    order_row.organization_id,
    order_row.id,
    'combo',
    combo_row.id,
    combo_row.name,
    combo_row.description,
    combo_row.image_path,
    target_quantity,
    combo_row.sale_price,
    combo_row.sale_price * target_quantity,
    case when target_quantity > 0 then total_cost / target_quantity else 0 end,
    total_cost,
    jsonb_build_object('selection_mode', combo_row.selection_mode),
    auth.uid()
  )
  returning * into item_row;

  for component_row in
    select * from public.combo_components
    where combo_id = combo_row.id
    order by sort_order asc, created_at asc
  loop
    if component_row.component_type = 'product' then
      select * into product_row from public.products where id = component_row.product_id;
      component_cost := product_row.average_purchase_cost;

      insert into public.order_combo_components (
        organization_id,
        order_item_id,
        component_type,
        product_id,
        name_snapshot,
        quantity,
        unit_price_snapshot,
        unit_cost_snapshot,
        included_minutes
      )
      values (
        order_row.organization_id,
        item_row.id,
        'product',
        product_row.id,
        product_row.name,
        component_row.quantity,
        product_row.sale_price,
        component_cost,
        component_row.included_minutes
      );

      if product_row.track_stock then
        insert into public.stock_reservations (
          organization_id,
          order_id,
          order_item_id,
          product_id,
          quantity,
          created_by
        )
        values (
          order_row.organization_id,
          order_row.id,
          item_row.id,
          product_row.id,
          component_row.quantity * target_quantity,
          auth.uid()
        );
      end if;
    else
      select * into service_row from public.services where id = component_row.service_id;

      insert into public.order_combo_components (
        organization_id,
        order_item_id,
        component_type,
        service_id,
        name_snapshot,
        quantity,
        unit_price_snapshot,
        included_minutes
      )
      values (
        order_row.organization_id,
        item_row.id,
        'service',
        service_row.id,
        service_row.name,
        component_row.quantity,
        coalesce(service_row.fixed_price, service_row.hourly_rate, 0),
        component_row.included_minutes
      );
    end if;
  end loop;

  perform public.recalculate_order_totals(order_row.id);
  perform public.log_audit(order_row.organization_id, 'order.item_added', 'order_item', item_row.id, jsonb_build_object('type', 'combo', 'combo_id', combo_row.id, 'quantity', target_quantity));

  return item_row;
end;
$$;

