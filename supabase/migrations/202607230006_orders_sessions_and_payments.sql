  perform set_config('app.order_write', '1', true);

  update public.orders
  set status = 'waiting_payment', updated_at = now()
  where id = order_row.id
  returning * into order_row;

  return order_row;
end;
$$;

create or replace function public.consume_order_stock(target_order_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  reservation_row public.stock_reservations;
  product_row public.products;
  next_quantity numeric;
begin
  perform set_config('app.order_write', '1', true);
  perform set_config('app.inventory_write', '1', true);

  for reservation_row in
    select * from public.stock_reservations
    where order_id = target_order_id
      and status = 'active'
    order by created_at asc
    for update
  loop
    select * into product_row from public.products where id = reservation_row.product_id for update;
    next_quantity := public.calculate_product_stock(product_row.id) - reservation_row.quantity;
    if next_quantity < 0 then
      raise exception 'Stock cannot become negative for product %.', product_row.name;
    end if;

    insert into public.stock_movements (
      organization_id,
      product_id,
      movement_type,
      quantity_delta,
      unit_cost,
      total_cost,
      reference_type,
      reference_id,
      comment,
      created_by
    )
    values (
      reservation_row.organization_id,
      reservation_row.product_id,
      'sale',
      -reservation_row.quantity,
      product_row.average_purchase_cost,
      -(reservation_row.quantity * product_row.average_purchase_cost),
      'order',
      reservation_row.order_item_id,
      'Order sale',
      auth.uid()
    );

    update public.stock_reservations
    set status = 'consumed', consumed_at = now()
    where id = reservation_row.id;

    perform public.reconcile_product_stock(reservation_row.product_id);
  end loop;
end;
$$;

create or replace function public.complete_order_payment(
  target_order_id uuid,
  target_method public.payment_method
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  order_row public.orders;
begin
  select * into order_row from public.orders where id = target_order_id for update;
  if order_row.id is null then raise exception 'Order was not found.'; end if;
  if order_row.status not in ('open', 'waiting_payment') then raise exception 'Order cannot be paid in current status.'; end if;
  if order_row.total_amount <= 0 then raise exception 'Order total must be greater than zero.'; end if;
  if not public.can_work_with_orders(order_row.organization_id) then raise exception 'You do not have access to this order.'; end if;
  if exists (select 1 from public.timed_sessions where order_id = order_row.id and status = 'active') then
    raise exception 'Active timed session must be completed first.';
  end if;
  if exists (select 1 from public.order_adjustment_requests where order_id = order_row.id and status = 'pending') then
    raise exception 'Pending adjustment requests must be reviewed first.';
  end if;
  if exists (select 1 from public.payments where order_id = order_row.id and status = 'completed') then
    raise exception 'Order already has completed payment.';
  end if;

  perform set_config('app.order_write', '1', true);

  insert into public.payments (
    organization_id,
    order_id,
    method,
    status,
    amount,
    received_by,
    completed_at
  )
  values (
    order_row.organization_id,
    order_row.id,
    target_method,
    'completed',
    order_row.total_amount,
    auth.uid(),
    now()
  );

  perform public.consume_order_stock(order_row.id);

  update public.orders
  set
    status = 'paid',
    paid_amount = total_amount,
    unpaid_amount = 0,
    closed_by = auth.uid(),
    closed_at = now(),
    updated_at = now()
  where id = order_row.id
  returning * into order_row;

  perform public.log_audit(order_row.organization_id, 'payment.completed', 'order', order_row.id, jsonb_build_object('method', target_method, 'amount', order_row.total_amount));

  return order_row;
end;
$$;

create or replace function public.mark_order_payment_refused(
  target_order_id uuid,
  target_comment text
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  order_row public.orders;
begin
  if length(btrim(coalesce(target_comment, ''))) = 0 then raise exception 'Payment refusal comment is required.'; end if;

  select * into order_row from public.orders where id = target_order_id for update;
  if order_row.id is null then raise exception 'Order was not found.'; end if;
  if order_row.status not in ('open', 'waiting_payment') then raise exception 'Order cannot be refused in current status.'; end if;
  if not public.can_work_with_orders(order_row.organization_id) then raise exception 'You do not have access to this order.'; end if;
  if exists (select 1 from public.timed_sessions where order_id = order_row.id and status = 'active') then
    raise exception 'Active timed session must be completed first.';
  end if;

  perform set_config('app.order_write', '1', true);
  perform public.consume_order_stock(order_row.id);

  update public.orders
  set
    status = 'payment_refused',
    paid_amount = 0,
    unpaid_amount = total_amount,
    payment_refusal_comment = target_comment,
    closed_by = auth.uid(),
    closed_at = now(),
    updated_at = now()
  where id = order_row.id
  returning * into order_row;

  perform public.log_audit(order_row.organization_id, 'payment.refused', 'order', order_row.id, jsonb_build_object('amount', order_row.total_amount, 'comment', target_comment));

  return order_row;
end;
$$;

create or replace view public.combo_availability
with (security_barrier = true)
as
with product_requirements as (
  select
    c.id as combo_id,
    c.organization_id,
    cc.product_id,
    sum(cc.quantity) as required_quantity
  from public.combos c
  join public.combo_components cc on cc.combo_id = c.id
  where cc.component_type = 'product'
    and cc.is_required = true
  group by c.id, c.organization_id, cc.product_id
),
component_availability as (
  select
    pr.combo_id,
    pr.organization_id,
    pr.product_id,
    pr.required_quantity,
    p.track_stock,
    p.status as product_status,
    public.calculate_available_product_stock(pr.product_id) as current_stock,
    case
      when p.track_stock = false then null
      else floor(public.calculate_available_product_stock(pr.product_id) / pr.required_quantity)
    end as available_quantity
  from product_requirements pr
  join public.products p on p.id = pr.product_id
)
select
  c.id as combo_id,
  c.organization_id,
  (
    c.status = 'active'
    and public.is_organization_member(c.organization_id)
    and not exists (
      select 1
      from component_availability ca
      where ca.combo_id = c.id
        and ca.track_stock = true
        and (ca.product_status <> 'active' or ca.current_stock < ca.required_quantity)
    )
  ) as is_available,
  case
    when not exists (select 1 from component_availability ca where ca.combo_id = c.id and ca.track_stock = true) then null
    else (
      select min(ca.available_quantity)::integer
      from component_availability ca
      where ca.combo_id = c.id
        and ca.track_stock = true
    )
  end as available_quantity,
  coalesce((
    select jsonb_agg(jsonb_build_object(
      'product_id', ca.product_id,
      'required_quantity', ca.required_quantity,
      'current_stock', ca.current_stock
    ))
    from component_availability ca
    where ca.combo_id = c.id
      and ca.track_stock = true
      and (ca.product_status <> 'active' or ca.current_stock < ca.required_quantity)
  ), '[]'::jsonb) as missing_components
from public.combos c
where public.is_platform_owner() or public.is_organization_member(c.organization_id);

