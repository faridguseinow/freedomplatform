create or replace function public.recalculate_order_totals(target_order_id uuid)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  order_row public.orders;
  next_subtotal numeric(14,2);
  next_paid numeric(14,2);
begin
  select * into order_row from public.orders where id = target_order_id for update;
  if order_row.id is null then raise exception 'Order was not found.'; end if;

  if current_setting('app.order_write', true) <> '1'
    and not public.is_organization_admin(order_row.organization_id)
  then
    raise exception 'Only trusted order functions can recalculate totals.';
  end if;

  select coalesce(sum(total_price), 0)::numeric(14,2)
  into next_subtotal
  from public.order_items
  where order_id = target_order_id
    and status = 'active';

  select coalesce(sum(amount), 0)::numeric(14,2)
  into next_paid
  from public.payments
  where order_id = target_order_id
    and status = 'completed';

  perform set_config('app.order_write', '1', true);

  update public.orders
  set
    subtotal = next_subtotal,
    total_amount = next_subtotal,
    paid_amount = next_paid,
    unpaid_amount = greatest(next_subtotal - next_paid, 0),
    updated_at = now()
  where id = target_order_id
  returning * into order_row;

  return order_row;
end;
$$;

create or replace function public.calculate_available_product_stock(target_product_id uuid)
returns numeric
language sql
stable
security definer
set search_path = public
as $$
  select (
    public.calculate_product_stock(target_product_id)
    - coalesce((
      select sum(sr.quantity)
      from public.stock_reservations sr
      where sr.product_id = target_product_id
        and sr.status = 'active'
    ), 0)
  )::numeric;
$$;

create or replace function public.release_order_item_reservations(
  target_order_item_id uuid,
  target_status public.stock_reservation_status default 'released'
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  perform set_config('app.order_write', '1', true);

  update public.stock_reservations
  set
    status = target_status,
    released_at = case when target_status in ('released', 'cancelled') then coalesce(released_at, now()) else released_at end,
