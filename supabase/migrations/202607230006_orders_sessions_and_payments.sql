create or replace function public.review_order_adjustment(
  target_request_id uuid,
  target_decision text,
  target_comment text default null
)
returns public.order_adjustment_requests
language plpgsql
security definer
set search_path = public
as $$
declare
  request_row public.order_adjustment_requests;
  item_row public.order_items;
  order_row public.orders;
  product_row public.products;
  delta numeric(14,3);
  available_quantity numeric;
begin
  if target_decision not in ('approved', 'rejected') then raise exception 'Decision must be approved or rejected.'; end if;

  select * into request_row from public.order_adjustment_requests where id = target_request_id for update;
  if request_row.id is null then raise exception 'Adjustment request was not found.'; end if;
  if request_row.status <> 'pending' then raise exception 'Adjustment request is already reviewed.'; end if;
  if not public.is_organization_admin(request_row.organization_id) then raise exception 'Only organization admins can review adjustment requests.'; end if;

  select * into order_row from public.orders where id = request_row.order_id for update;
  if order_row.id is null then raise exception 'Order was not found.'; end if;
  if order_row.status not in ('open', 'waiting_payment') then raise exception 'Only active orders can be corrected.'; end if;

  perform set_config('app.order_write', '1', true);

  if target_decision = 'approved' then
    if request_row.request_type = 'remove_order_item' then
      select * into item_row from public.order_items where id = request_row.order_item_id for update;
      if item_row.id is null then raise exception 'Order item was not found.'; end if;
      if item_row.status <> 'active' then raise exception 'Only active items can be removed.'; end if;

      update public.order_items
      set status = 'removed', removed_by = auth.uid(), removed_at = now(), removal_reason = request_row.reason, updated_at = now()
      where id = item_row.id;

      perform public.release_order_item_reservations(item_row.id, 'released');
      perform public.recalculate_order_totals(order_row.id);
    elsif request_row.request_type = 'change_quantity' then
      select * into item_row from public.order_items where id = request_row.order_item_id for update;
      if item_row.id is null then raise exception 'Order item was not found.'; end if;
      if item_row.status <> 'active' then raise exception 'Only active items can be changed.'; end if;
      if request_row.requested_quantity is null or request_row.requested_quantity <= 0 then raise exception 'Requested quantity is required.'; end if;
      if item_row.item_type = 'timed_session' then raise exception 'Timed session item quantity cannot be changed.'; end if;

      delta := request_row.requested_quantity - item_row.quantity;
      if delta > 0 and item_row.item_type = 'product' then
        select * into product_row from public.products where id = item_row.product_id for update;
        if product_row.track_stock then
          available_quantity := public.calculate_available_product_stock(product_row.id);
          if available_quantity < delta then
            raise exception 'Not enough available stock for quantity increase.';
          end if;
          insert into public.stock_reservations (organization_id, order_id, order_item_id, product_id, quantity, created_by)
          values (item_row.organization_id, item_row.order_id, item_row.id, product_row.id, delta, auth.uid());
        end if;
      elsif delta < 0 then
        update public.stock_reservations
        set quantity = greatest(quantity + delta, 0)
        where order_item_id = item_row.id
          and status = 'active';

        update public.stock_reservations
        set status = 'released', released_at = now()
        where order_item_id = item_row.id
          and status = 'active'
          and quantity <= 0;
      end if;

      update public.order_items
      set
        quantity = request_row.requested_quantity,
        total_price = unit_price * request_row.requested_quantity,
        total_cost_snapshot = coalesce(unit_cost_snapshot, 0) * request_row.requested_quantity,
        updated_at = now()
      where id = item_row.id;

      perform public.recalculate_order_totals(order_row.id);
    elsif request_row.request_type = 'cancel_order' then
      update public.order_items
      set status = 'cancelled', removed_by = auth.uid(), removed_at = now(), removal_reason = request_row.reason, updated_at = now()
      where order_id = order_row.id
        and status = 'active';

      update public.stock_reservations
      set status = 'cancelled', released_at = now()
      where order_id = order_row.id
        and status = 'active';

      update public.orders
      set status = 'cancelled', closed_by = auth.uid(), closed_at = now(), updated_at = now()
      where id = order_row.id;
    end if;
  end if;

  update public.order_adjustment_requests
  set
    status = target_decision::public.adjustment_request_status,
    reviewed_by = auth.uid(),
    reviewed_at = now(),
    review_comment = nullif(btrim(target_comment), '')
  where id = request_row.id
  returning * into request_row;

  perform public.log_audit(request_row.organization_id, 'adjustment.' || target_decision, 'order_adjustment_request', request_row.id, jsonb_build_object('order_id', request_row.order_id));

  return request_row;
end;
$$;

create or replace function public.set_order_waiting_payment(target_order_id uuid)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  order_row public.orders;
begin
  select * into order_row from public.orders where id = target_order_id for update;
  if order_row.id is null then raise exception 'Order was not found.'; end if;
  if order_row.status <> 'open' then raise exception 'Only open orders can wait for payment.'; end if;
  if not public.can_work_with_orders(order_row.organization_id) then raise exception 'You do not have access to this order.'; end if;
