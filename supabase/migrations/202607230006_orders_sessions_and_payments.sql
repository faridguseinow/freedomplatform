$$;

create or replace function public.create_order(
  target_place_id uuid default null,
  target_customer_label text default null,
  target_comment text default null
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  target_organization_id uuid;
  place_row public.places;
  order_row public.orders;
begin
  if target_place_id is not null then
    select * into place_row from public.places where id = target_place_id for update;
    if place_row.id is null then raise exception 'Place was not found.'; end if;
    if place_row.status <> 'active' then raise exception 'Place is not active.'; end if;
    target_organization_id := place_row.organization_id;
  else
    target_organization_id := public.current_user_primary_organization_id();
  end if;

  if target_organization_id is null then
    raise exception 'Organization could not be determined.';
  end if;

  if not public.can_work_with_orders(target_organization_id) then
    raise exception 'You do not have access to this organization.';
  end if;

  if not exists (select 1 from public.organizations o where o.id = target_organization_id and o.status = 'active') then
    raise exception 'Organization is not active.';
  end if;

  if target_place_id is not null then
    if exists (
      select 1 from public.orders o
      where o.organization_id = target_organization_id
        and o.place_id = target_place_id
        and o.status in ('open', 'waiting_payment')
    ) then
      raise exception 'Place already has an active order.';
    end if;

    if exists (
      select 1 from public.timed_sessions ts
      where ts.organization_id = target_organization_id
        and ts.place_id = target_place_id
        and ts.status = 'active'
    ) then
      raise exception 'Place already has an active timed session.';
    end if;
  end if;

  perform set_config('app.order_write', '1', true);

  insert into public.orders (
    organization_id,
    place_id,
    current_place_name_snapshot,
    customer_label,
    comment,
    opened_by
  )
  values (
    target_organization_id,
    target_place_id,
    place_row.name,
    nullif(btrim(target_customer_label), ''),
    nullif(btrim(target_comment), ''),
    auth.uid()
  )
  returning * into order_row;

  perform public.log_audit(target_organization_id, 'order.created', 'order', order_row.id, jsonb_build_object('place_id', target_place_id));

  return order_row;
end;
$$;

create or replace function public.add_product_to_order(
  target_order_id uuid,
  target_product_id uuid,
  target_quantity numeric
)
returns public.order_items
language plpgsql
security definer
set search_path = public
as $$
declare
  order_row public.orders;
  product_row public.products;
  item_row public.order_items;
  existing_item_id uuid;
  next_quantity numeric(14,3);
  available_quantity numeric;
begin
  if target_quantity <= 0 then raise exception 'Quantity must be greater than zero.'; end if;

  select * into order_row from public.orders where id = target_order_id for update;
  if order_row.id is null then raise exception 'Order was not found.'; end if;
  if order_row.status <> 'open' then raise exception 'Only open orders can be changed.'; end if;
  if not public.can_work_with_orders(order_row.organization_id) then raise exception 'You do not have access to this order.'; end if;

  select * into product_row from public.products where id = target_product_id for update;
  if product_row.id is null then raise exception 'Product was not found.'; end if;
  if product_row.organization_id <> order_row.organization_id or product_row.status <> 'active' then
    raise exception 'Product is not active in this organization.';
  end if;

  if product_row.track_stock then
    available_quantity := public.calculate_available_product_stock(product_row.id);
    if available_quantity < target_quantity then
      raise exception 'Not enough available stock for product %. Available: %.', product_row.name, available_quantity;
    end if;
  end if;

  perform set_config('app.order_write', '1', true);

