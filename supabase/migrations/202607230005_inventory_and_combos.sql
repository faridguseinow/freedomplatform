-- Inventory ledger and combos foundation.
-- No real data, emails, UUIDs, passwords, or service-role secrets are stored here.

do $$
begin
  if not exists (select 1 from pg_type where typnamespace = 'public'::regnamespace and typname = 'stock_movement_type') then
    create type public.stock_movement_type as enum (
      'opening_balance',
      'purchase',
      'sale',
      'return_in',
      'return_out',
      'write_off',
      'adjustment_in',
      'adjustment_out',
      'combo_reservation',
      'combo_release',
      'order_reservation',
      'order_release',
      'transfer_in',
      'transfer_out'
    );
  end if;

  if not exists (select 1 from pg_type where typnamespace = 'public'::regnamespace and typname = 'stock_document_status') then
    create type public.stock_document_status as enum ('draft', 'posted', 'cancelled');
  end if;

  if not exists (select 1 from pg_type where typnamespace = 'public'::regnamespace and typname = 'combo_status') then
    create type public.combo_status as enum ('active', 'inactive', 'archived');
  end if;

  if not exists (select 1 from pg_type where typnamespace = 'public'::regnamespace and typname = 'combo_component_type') then
    create type public.combo_component_type as enum ('product', 'service');
  end if;

  if not exists (select 1 from pg_type where typnamespace = 'public'::regnamespace and typname = 'combo_selection_mode') then
    create type public.combo_selection_mode as enum ('fixed', 'choice');
  end if;
end
$$;

