$$;

create or replace function public.prevent_catalog_restricted_write()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' then
    if new.organization_id is distinct from old.organization_id
      or new.created_by is distinct from old.created_by
    then
      raise exception 'Cannot update protected catalog fields.';
    end if;
  end if;

  if not exists (
    select 1
    from public.organizations o
    where o.id = new.organization_id
      and o.status = 'active'
  ) then
    raise exception 'Organization is not active.';
  end if;

  if tg_table_name = 'products'
    and tg_op = 'UPDATE'
    and current_setting('app.inventory_write', true) = '1'
  then
    return new;
  end if;

  if not (
    public.is_platform_owner()
    or public.is_organization_admin(new.organization_id)
  ) then
    raise exception 'Only organization admins can write catalog data for this organization.';
  end if;

  return new;
end;
$$;

create or replace function public.assert_combo_scope()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' then
    if new.organization_id is distinct from old.organization_id
      or new.created_by is distinct from old.created_by
    then
      raise exception 'Cannot update protected combo fields.';
    end if;
  end if;

  if new.category_id is not null and not exists (
    select 1
    from public.catalog_categories c
    where c.id = new.category_id
      and c.organization_id = new.organization_id
      and c.type = 'product'
      and c.status <> 'archived'
  ) then
    raise exception 'Combo category must be an active product category in the same organization.';
  end if;

  if not (public.is_platform_owner() or public.is_organization_admin(new.organization_id)) then
    raise exception 'Only organization admins can write combos.';
  end if;

  if not exists (select 1 from public.organizations o where o.id = new.organization_id and o.status = 'active') then
    raise exception 'Organization is not active.';
  end if;

  return new;
end;
$$;

create or replace function public.assert_combo_component_scope()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if not exists (select 1 from public.combos c where c.id = new.combo_id and c.organization_id = new.organization_id) then
    raise exception 'Combo does not belong to this organization.';
  end if;

  if new.component_type = 'product' and not exists (
    select 1 from public.products p
    where p.id = new.product_id
      and p.organization_id = new.organization_id
      and p.status <> 'archived'
  ) then
    raise exception 'Product component does not belong to this organization or is archived.';
  end if;

  if new.component_type = 'service' and not exists (
    select 1 from public.services s
    where s.id = new.service_id
      and s.organization_id = new.organization_id
      and s.status <> 'archived'
  ) then
    raise exception 'Service component does not belong to this organization or is archived.';
  end if;

  if new.component_type = 'service'
    and new.included_minutes is not null
    and not exists (
      select 1 from public.services s
      where s.id = new.service_id
        and s.pricing_type = 'hourly'
    )
  then
    raise exception 'Included minutes are allowed only for hourly services.';
  end if;

  if not (public.is_platform_owner() or public.is_organization_admin(new.organization_id)) then
    raise exception 'Only organization admins can write combo components.';
  end if;

  return new;
end;
$$;

