create or replace function public.inventory_quantity_sign(document_type public.stock_movement_type)
returns integer
language sql
immutable
as $$
  select case
    when document_type in ('opening_balance', 'purchase', 'return_in', 'adjustment_in', 'transfer_in') then 1
    when document_type in ('sale', 'return_out', 'write_off', 'adjustment_out', 'transfer_out') then -1
    else 0
  end;
$$;

create or replace function public.calculate_product_stock(target_product_id uuid)
returns numeric
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(sum(sm.quantity_delta), 0)::numeric
  from public.stock_movements sm
  where sm.product_id = target_product_id;
$$;

create or replace function public.reconcile_product_stock(target_product_id uuid)
returns public.products
language plpgsql
security definer
set search_path = public
as $$
declare
  product_row public.products;
  calculated_quantity numeric(14,3);
  calculated_average numeric(14,4);
begin
  select * into product_row from public.products where id = target_product_id;
  if product_row.id is null then
    raise exception 'Product was not found.';
  end if;

  if current_setting('app.inventory_write', true) <> '1'
    and not (public.is_platform_owner() or public.is_organization_admin(product_row.organization_id))
  then
    raise exception 'Only organization admins can reconcile stock.';
  end if;

  select coalesce(sum(quantity_delta), 0)::numeric(14,3)
  into calculated_quantity
  from public.stock_movements
  where product_id = target_product_id;

  select coalesce(
    sum(case when quantity_delta > 0 and unit_cost is not null then quantity_delta * unit_cost else 0 end)
    / nullif(sum(case when quantity_delta > 0 and unit_cost is not null then quantity_delta else 0 end), 0),
    0
  )::numeric(14,4)
  into calculated_average
  from public.stock_movements
  where product_id = target_product_id;

  perform set_config('app.inventory_write', '1', true);

  update public.products
  set
    stock_quantity = calculated_quantity,
    average_purchase_cost = calculated_average,
    updated_at = now()
  where id = target_product_id
  returning * into product_row;

  return product_row;
end;
$$;

create or replace view public.product_stock_balances
with (security_barrier = true)
as
select
  p.organization_id,
  p.id as product_id,
  public.calculate_product_stock(p.id)::numeric(14,3) as calculated_quantity,
  p.stock_quantity as cached_quantity,
  (public.calculate_product_stock(p.id) - p.stock_quantity)::numeric(14,3) as variance
from public.products p
where public.is_platform_owner() or public.is_organization_admin(p.organization_id);

create or replace function public.assert_stock_document_scope()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' then
    if new.organization_id is distinct from old.organization_id
      or new.created_by is distinct from old.created_by
      or (old.status = 'posted' and new.status = 'draft')
    then
      raise exception 'Cannot update protected stock document fields.';
    end if;
  end if;

  if not exists (select 1 from public.organizations o where o.id = new.organization_id and o.status = 'active') then
    raise exception 'Organization is not active.';
  end if;

  if current_setting('app.inventory_write', true) = '1' then
    return new;
  end if;

  if not (public.is_platform_owner() or public.is_organization_admin(new.organization_id)) then
    raise exception 'Only organization admins can write stock documents.';
  end if;

  return new;
end;
$$;

create or replace function public.assert_stock_item_scope()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  document_status public.stock_document_status;
begin
  select status into document_status
  from public.stock_documents
  where id = new.document_id and organization_id = new.organization_id;

  if document_status is null then
    raise exception 'Stock document does not belong to this organization.';
  end if;

  if not exists (select 1 from public.products p where p.id = new.product_id and p.organization_id = new.organization_id and p.track_stock = true) then
    raise exception 'Product does not belong to this organization or is not stock-tracked.';
  end if;

  if current_setting('app.inventory_write', true) = '1' then
    return new;
  end if;

  if document_status <> 'draft' then
    raise exception 'Posted or cancelled document items cannot be edited.';
  end if;

  if exists (select 1 from public.products p where p.id = new.product_id and p.status = 'archived') then
    raise exception 'Archived products cannot be used in stock documents.';
  end if;

  if not (public.is_platform_owner() or public.is_organization_admin(new.organization_id)) then
    raise exception 'Only organization admins can write stock items.';
  end if;

  return new;
end;
$$;

