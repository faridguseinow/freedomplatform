create or replace function public.post_stock_document(target_document_id uuid)
returns public.stock_documents
language plpgsql
security definer
set search_path = public
as $$
declare
  document_row public.stock_documents;
  item_row public.stock_document_items;
  sign integer;
  next_quantity numeric(14,3);
begin
  select * into document_row from public.stock_documents where id = target_document_id;
  if document_row.id is null then raise exception 'Stock document was not found.'; end if;
  if document_row.status <> 'draft' then raise exception 'Only draft documents can be posted.'; end if;
  if not (public.is_platform_owner() or public.is_organization_admin(document_row.organization_id)) then
    raise exception 'Only organization admins can post stock documents.';
  end if;
  if not exists (select 1 from public.organizations o where o.id = document_row.organization_id and o.status = 'active') then
    raise exception 'Organization is not active.';
  end if;

  sign := public.inventory_quantity_sign(document_row.type);
  if sign = 0 then raise exception 'This stock document type is not postable at this stage.'; end if;

  if not exists (select 1 from public.stock_document_items where document_id = target_document_id) then
    raise exception 'Document must contain at least one item.';
  end if;

  perform set_config('app.inventory_write', '1', true);

  for item_row in
    select * from public.stock_document_items where document_id = target_document_id order by created_at asc
  loop
    if not exists (select 1 from public.products p where p.id = item_row.product_id and p.organization_id = document_row.organization_id and p.track_stock = true) then
      raise exception 'Document item product does not belong to this organization.';
    end if;

    next_quantity := public.calculate_product_stock(item_row.product_id) + (item_row.quantity * sign);
    if next_quantity < 0 then
      raise exception 'Stock cannot become negative.';
    end if;

    insert into public.stock_movements (
      organization_id,
      product_id,
      document_id,
      document_item_id,
      movement_type,
      quantity_delta,
      unit_cost,
      total_cost,
      reference_type,
      reference_id,
      comment,
      created_by
    )
    values (
      document_row.organization_id,
      item_row.product_id,
      document_row.id,
      item_row.id,
      document_row.type,
      item_row.quantity * sign,
      item_row.unit_cost,
      coalesce(item_row.line_total, item_row.quantity * coalesce(item_row.unit_cost, 0)),
      'stock_document',
      document_row.id,
      item_row.comment,
      auth.uid()
    );

    perform public.reconcile_product_stock(item_row.product_id);
  end loop;

  update public.stock_documents
  set status = 'posted', posted_by = auth.uid(), posted_at = now(), updated_at = now()
  where id = target_document_id
  returning * into document_row;

  return document_row;
end;
$$;

create or replace function public.cancel_stock_document(target_document_id uuid, target_reason text)
returns public.stock_documents
language plpgsql
security definer
set search_path = public
as $$
declare
  document_row public.stock_documents;
  movement_row public.stock_movements;
  next_quantity numeric(14,3);
begin
  if length(btrim(coalesce(target_reason, ''))) = 0 then
    raise exception 'Cancellation reason is required.';
  end if;

  select * into document_row from public.stock_documents where id = target_document_id;
  if document_row.id is null then raise exception 'Stock document was not found.'; end if;
  if document_row.status = 'cancelled' then raise exception 'Document is already cancelled.'; end if;
  if not (public.is_platform_owner() or public.is_organization_admin(document_row.organization_id)) then
    raise exception 'Only organization admins can cancel stock documents.';
  end if;

  perform set_config('app.inventory_write', '1', true);

  if document_row.status = 'posted' then
    for movement_row in
      select * from public.stock_movements where document_id = target_document_id order by created_at asc
    loop
      next_quantity := public.calculate_product_stock(movement_row.product_id) - movement_row.quantity_delta;
      if next_quantity < 0 then
        raise exception 'Cancellation would make stock negative.';
      end if;

      insert into public.stock_movements (
        organization_id,
        product_id,
        document_id,
        document_item_id,
        movement_type,
        quantity_delta,
        unit_cost,
        total_cost,
        reference_type,
        reference_id,
        comment,
        created_by
      )
      values (
        movement_row.organization_id,
        movement_row.product_id,
        document_row.id,
        movement_row.document_item_id,
        movement_row.movement_type,
        -movement_row.quantity_delta,
        movement_row.unit_cost,
        -coalesce(movement_row.total_cost, 0),
        'stock_document_cancellation',
        document_row.id,
        target_reason,
        auth.uid()
      );

      perform public.reconcile_product_stock(movement_row.product_id);
    end loop;
  end if;

  update public.stock_documents
  set
    status = 'cancelled',
    cancelled_by = auth.uid(),
    cancelled_at = now(),
    cancellation_reason = target_reason,
    updated_at = now()
  where id = target_document_id
  returning * into document_row;

  return document_row;
end;
$$;

create or replace function public.create_opening_stock_document(
  target_product_id uuid,
  target_quantity numeric,
  target_unit_cost numeric default null,
  target_comment text default null
)
returns public.stock_documents
language plpgsql
security definer
set search_path = public
as $$
declare
  product_row public.products;
  document_row public.stock_documents;
begin
  if target_quantity <= 0 then raise exception 'Opening quantity must be greater than zero.'; end if;
  if target_unit_cost is not null and target_unit_cost < 0 then raise exception 'Unit cost cannot be negative.'; end if;

  select * into product_row from public.products where id = target_product_id;
  if product_row.id is null then raise exception 'Product was not found.'; end if;
  if not (public.is_platform_owner() or public.is_organization_admin(product_row.organization_id)) then
    raise exception 'Only organization admins can create opening stock.';
  end if;

  insert into public.stock_documents (organization_id, type, document_date, comment, total_amount, created_by)
  values (
    product_row.organization_id,
    'opening_balance',
    now(),
    target_comment,
    target_quantity * coalesce(target_unit_cost, product_row.purchase_price, 0),
    auth.uid()
  )
  returning * into document_row;

  insert into public.stock_document_items (organization_id, document_id, product_id, quantity, unit_cost, line_total, comment)
  values (
    product_row.organization_id,
    document_row.id,
    product_row.id,
    target_quantity,
    coalesce(target_unit_cost, product_row.purchase_price),
    target_quantity * coalesce(target_unit_cost, product_row.purchase_price, 0),
    target_comment
  );

  return public.post_stock_document(document_row.id);
end;
$$;

create or replace function public.set_combo_status(target_id uuid, target_status public.combo_status)
returns public.combos
language plpgsql
security definer
set search_path = public
as $$
declare
  combo_row public.combos;
begin
  select * into combo_row from public.combos where id = target_id;
  if combo_row.id is null then raise exception 'Combo was not found.'; end if;
  if not (public.is_platform_owner() or public.is_organization_admin(combo_row.organization_id)) then
    raise exception 'Only organization admins can change combo status.';
  end if;
  update public.combos set status = target_status where id = target_id returning * into combo_row;
  return combo_row;
end;
$$;

create or replace view public.combo_availability
with (security_barrier = true)
as
with product_requirements as (
  select
    c.id as combo_id,
    c.organization_id,
    cc.product_id,
    sum(cc.quantity) as required_quantity
  from public.combos c
  join public.combo_components cc on cc.combo_id = c.id
  where cc.component_type = 'product'
    and cc.is_required = true
  group by c.id, c.organization_id, cc.product_id
),
component_availability as (
  select
    pr.combo_id,
    pr.organization_id,
    pr.product_id,
    pr.required_quantity,
    p.track_stock,
    p.status as product_status,
    public.calculate_product_stock(pr.product_id) as current_stock,
    case
      when p.track_stock = false then null
      else floor(public.calculate_product_stock(pr.product_id) / pr.required_quantity)
    end as available_quantity
  from product_requirements pr
  join public.products p on p.id = pr.product_id
)
select
  c.id as combo_id,
  c.organization_id,
  (
    c.status = 'active'
    and public.is_organization_member(c.organization_id)
    and not exists (
      select 1
      from component_availability ca
      where ca.combo_id = c.id
        and ca.track_stock = true
        and (ca.product_status <> 'active' or ca.current_stock < ca.required_quantity)
    )
  ) as is_available,
  case
    when not exists (select 1 from component_availability ca where ca.combo_id = c.id and ca.track_stock = true) then null
    else (
      select min(ca.available_quantity)::integer
      from component_availability ca
      where ca.combo_id = c.id
        and ca.track_stock = true
    )
  end as available_quantity,
  coalesce((
    select jsonb_agg(jsonb_build_object(
      'product_id', ca.product_id,
      'required_quantity', ca.required_quantity,
      'current_stock', ca.current_stock
    ))
    from component_availability ca
    where ca.combo_id = c.id
      and ca.track_stock = true
      and (ca.product_status <> 'active' or ca.current_stock < ca.required_quantity)
  ), '[]'::jsonb) as missing_components
from public.combos c
where public.is_platform_owner() or public.is_organization_member(c.organization_id);

create or replace view public.employee_combos
with (security_barrier = true)
as
select
  c.id,
  c.organization_id,
  c.category_id,
  c.name,
  c.description,
  c.image_path,
  c.sale_price,
  ca.available_quantity,
  coalesce((
    select jsonb_agg(jsonb_build_object(
      'type', cc.component_type,
      'name', coalesce(p.name, s.name),
      'quantity', cc.quantity,
      'included_minutes', cc.included_minutes
    ) order by cc.sort_order)
    from public.combo_components cc
    left join public.products p on p.id = cc.product_id
    left join public.services s on s.id = cc.service_id
    where cc.combo_id = c.id
  ), '[]'::jsonb) as component_preview
from public.combos c
join public.combo_availability ca on ca.combo_id = c.id
where c.status = 'active'
  and ca.is_available = true
  and public.is_organization_member(c.organization_id);

do $$
declare
  product_row public.products;
  document_row public.stock_documents;
begin
  perform set_config('app.inventory_write', '1', true);

  for product_row in
    select *
    from public.products p
    where p.track_stock = true
      and p.stock_quantity > 0
      and not exists (
        select 1
        from public.stock_movements sm
        where sm.product_id = p.id
          and sm.movement_type = 'opening_balance'
          and sm.reference_type = 'migration_202607230005'
      )
  loop
    insert into public.stock_documents (
      organization_id,
      type,
      status,
      document_date,
      comment,
      total_amount,
      created_by,
      posted_by,
      posted_at
    )
    values (
      product_row.organization_id,
      'opening_balance',
      'posted',
      now(),
      'Migrated opening balance from products.stock_quantity',
      product_row.stock_quantity * coalesce(product_row.purchase_price, 0),
      product_row.created_by,
      product_row.created_by,
      now()
    )
    returning * into document_row;

    insert into public.stock_document_items (
      organization_id,
      document_id,
      product_id,
      quantity,
      unit_cost,
      line_total,
      comment
    )
    values (
      product_row.organization_id,
      document_row.id,
      product_row.id,
      product_row.stock_quantity,
      product_row.purchase_price,
      product_row.stock_quantity * coalesce(product_row.purchase_price, 0),
      'Migrated opening balance'
    );

    insert into public.stock_movements (
      organization_id,
      product_id,
      document_id,
      document_item_id,
      movement_type,
      quantity_delta,
      unit_cost,
      total_cost,
      reference_type,
      reference_id,
      comment,
      created_by
    )
    select
      product_row.organization_id,
      product_row.id,
      document_row.id,
      sdi.id,
      'opening_balance',
      product_row.stock_quantity,
      product_row.purchase_price,
      product_row.stock_quantity * coalesce(product_row.purchase_price, 0),
      'migration_202607230005',
      product_row.id,
      'Migrated opening balance',
      product_row.created_by
    from public.stock_document_items sdi
    where sdi.document_id = document_row.id
      and sdi.product_id = product_row.id;

    perform public.reconcile_product_stock(product_row.id);
  end loop;
end
$$;

